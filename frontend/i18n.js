let CURRENT_LANG = (() => {
  try { return localStorage.getItem("lang") || "kz"; } catch { return "kz"; }
})();

function t(key) {
  return (I18N[CURRENT_LANG] && I18N[CURRENT_LANG][key]) || I18N.kz[key] || key;
}

function gradeText(letter) {
  return t("grade_" + String(letter || "F")[0]);
}

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });  // our own strings only
  document.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.querySelectorAll(".lang-switch button").forEach(b => {
    b.classList.toggle("active", b.dataset.lang === CURRENT_LANG);
  });
  document.documentElement.lang = CURRENT_LANG === "kz" ? "kk" : CURRENT_LANG;
}

function setLang(lang) {
  CURRENT_LANG = lang;
  try { localStorage.setItem("lang", lang); } catch {}
  applyI18n();
  if (typeof onLangChange === "function") onLangChange();
}

// Shared helpers for both pages
async function apiCall(method, path, body, { isForm = false, token = null, raw = false, timeoutMs = 0 } = {}) {
  const opts = { method, headers: {} };
  let timer = null;
  if (timeoutMs) {
    const ctrl = new AbortController();
    opts.signal = ctrl.signal;
    timer = setTimeout(() => ctrl.abort(), timeoutMs);
  }
  if (token) opts.headers["Authorization"] = "Bearer " + token;
  if (body) {
    if (isForm) opts.body = body;
    else { opts.headers["Content-Type"] = "application/json"; opts.body = JSON.stringify(body); }
  }
  let r;
  try { r = await fetch(path, opts); }
  catch (e) { throw new Error(t(e && e.name === "AbortError" ? "err_timeout" : "err_network")); }
  finally { clearTimeout(timer); }
  if (!r.ok) {
    let code = "";
    try {
      const j = await r.json();
      code = typeof j.detail === "string" ? j.detail : (Array.isArray(j.detail) ? "validation" : "");
    } catch {}
    const err = new Error(code.startsWith("ai_error") ? "AI: " + code.slice(10) : (t("err_" + code) !== "err_" + code ? t("err_" + code) : (code || r.statusText || "HTTP " + r.status)));
    err.status = r.status;
    err.code = code;
    throw err;
  }
  return raw ? r : r.json();
}

function escapeHtml(s) {
  return String(s ?? "").replace(/[&<>"']/g, m => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", "\"": "&quot;", "'": "&#39;" }[m]));
}

function formatAnswer(v) {
  if (v === null || v === undefined || v === "") return "—";
  if (typeof v === "object") return Object.entries(v).map(([k, x]) => `${k} → ${x || "—"}`).join("; ");
  return String(v);
}

function fmtDuration(sec) {
  if (!sec && sec !== 0) return "—";
  const m = Math.floor(sec / 60), s = sec % 60;
  return `${m}:${String(s).padStart(2, "0")}`;
}
